import { act, renderHook, waitFor } from "@testing-library/react";
import type { ReactNode } from "react";
import { beforeEach, expect, it, vi } from "vitest";
const network = vi.hoisted(()=>({from:vi.fn(),getSession:vi.fn(),onAuthStateChange:vi.fn()}));
vi.mock("@/lib/previewMode",()=>({isPreviewMode:true,isDesignPreview:true,isAccountPreview:false}));
vi.mock("@/integrations/supabase/client",()=>({supabase:{from:network.from,auth:{getSession:network.getSession,onAuthStateChange:network.onAuthStateChange}}}));
import { AuthProvider, useAuth } from "@/hooks/useAuth";
import { FinanceProvider, useFinanceStore } from "./financeStore";
const wrapper=({children}:{children:ReactNode})=><AuthProvider><FinanceProvider>{children}</FinanceProvider></AuthProvider>;
beforeEach(()=>{localStorage.clear();vi.clearAllMocks();});
it("keeps design changes local, ignores unowned legacy data and preserves the saved preview on reload",async()=>{
 localStorage.setItem("fin_banks",JSON.stringify([{id:"private-legacy-card"}]));
 localStorage.setItem("fin_user_real-account",JSON.stringify({banks:[{id:"private-real-card"}]}));
 const original=localStorage.getItem("fin_user_real-account");
 const first=renderHook(()=>({store:useFinanceStore(),auth:useAuth()}),{wrapper});
 await waitFor(()=>expect(first.result.current.store.cloudReady).toBe(true));
 expect(first.result.current.auth.user?.id).toBe("preview-user");
 expect(first.result.current.auth.session).toBeNull();
 expect(first.result.current.store.banks.some(bank=>bank.id==="private-legacy-card")).toBe(false);
 const month=first.result.current.store.selectedMonth;
 act(()=>first.result.current.store.addCashflowItem(month,"expenses","Teste somente local",12.34));
 await waitFor(()=>expect(first.result.current.store.syncStatus).toBe("saved"));
 first.unmount();
 const second=renderHook(()=>useFinanceStore(),{wrapper});
 await waitFor(()=>expect(second.result.current.cloudReady).toBe(true));
 expect(second.result.current.cashflowMonths[month].expenses.some(item=>item.label==="Teste somente local"&&item.amount===12.34)).toBe(true);
 expect(localStorage.getItem("fin_user_real-account")).toBe(original);
 expect(network.from).not.toHaveBeenCalled();
 expect(network.getSession).not.toHaveBeenCalled();
 expect(network.onAuthStateChange).not.toHaveBeenCalled();
});
